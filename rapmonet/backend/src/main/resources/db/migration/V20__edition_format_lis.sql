CREATE TABLE fmt_modification (
    id           BIGSERIAL     PRIMARY KEY,
    format_code  VARCHAR(30)   NOT NULL,
    objet        VARCHAR(120)  NOT NULL,     -- ex. TC 49 / TCR 1, champ LIS_TRANSACTION_TIME
    action       VARCHAR(40)   NOT NULL,     -- CHAMP_MODIFIE, CHAMP_CREE, STRUCTURE_TCR, TC_MODIFIE, TC_CREE
    motif        VARCHAR(500)  NOT NULL,
    avant        TEXT,
    apres        TEXT          NOT NULL,
    modifie_par  VARCHAR(50),
    modifie_le   TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_fmt_modification ON fmt_modification (format_code, id DESC);
